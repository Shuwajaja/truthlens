// Rebuild vector sources and icons from the single theme palette; no network access.
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {openSync} from 'fontkit';
const root=new URL('../',import.meta.url);
const theme=await readFile(new URL('src/theme.css',root),'utf8');
const palette=Object.fromEntries([...theme.matchAll(/--(bg|text|brand):\s*(#[\da-f]{6});/gi)].map(match=>[match[1],match[2]]));
if(!['bg','text','brand'].every(key=>palette[key]))throw new Error('Missing brand palette tokens');
const resolve=text=>text.replace(/var\(--(bg|text|brand)\)/g,(_,token)=>palette[token]);
const body=text=>text.replace(/^<svg[^>]*>\s*/,'').replace(/\s*<\/svg>\s*$/,'');
const iconSource=await readFile(new URL('brand/logo-icon.svg',root),'utf8');
const mark=body(await readFile(new URL('brand/wordmark-mark.svg',root),'utf8'));
const font=openSync(fileURLToPath(new URL('node_modules/@fontsource/inter/files/inter-latin-600-normal.woff2',root)));
const run=font.layout('TruthLens');
if(run.glyphs.length!==9)throw new Error('Unexpected wordmark shaping');
const scale=86/font.unitsPerEm;
let advance=0;
const glyphs=run.glyphs.map((glyph,index)=>{
 const pos=run.positions[index];
 const result=`<path fill="var(--${index<5?'brand':'text'})" transform="translate(${(150+(advance+pos.xOffset)*scale).toFixed(6)} ${(110-pos.yOffset*scale).toFixed(6)}) scale(${scale.toFixed(9)} -${scale.toFixed(9)})" d="${glyph.path.toSVG()}"/>`;
 advance+=pos.xAdvance;return result;
}).join('\n');
const width=Math.ceil(150+advance*scale+4);
const notice='<!-- Generated by scripts/build-brand.mjs from theme.css and brand/*.svg. -->\n';
const wordmark=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} 160" role="img" aria-label="TruthLens">\n${mark}\n${glyphs}\n</svg>\n`;
const favicon=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 160 160"><rect width="160" height="160" rx="12" fill="var(--bg)"/><g transform="translate(16 0)">${body(iconSource)}</g></svg>\n`;
const assets={'logo-icon.svg':notice+resolve(iconSource),'logo-wordmark.svg':notice+resolve(wordmark),'favicon.svg':notice+resolve(favicon)};
if(process.argv.includes('--check')){
 for(const [name,content]of Object.entries(assets))if(await readFile(new URL('public/'+name,root),'utf8')!==content)throw new Error('Run npm run brand:build');
 const png=await readFile(new URL('public/apple-touch-icon.png',root));
 const ico=await readFile(new URL('public/favicon.ico',root));
 if(png.readUInt32BE(16)!==180||png.readUInt32BE(20)!==180||ico.readUInt16LE(2)!==1||ico[6]!==32||ico[7]!==32)throw new Error('Invalid icon dimensions');
 console.log('Brand SVGs match theme tokens; favicon32 and touch icon180 present.');
}else{
 for(const [name,content]of Object.entries(assets))await writeFile(new URL('public/'+name,root),content);
 process.env.PLAYWRIGHT_BROWSERS_PATH??=fileURLToPath(new URL('../.venv/playwright',root));
 const {chromium}=await import('playwright');
 const browser=await chromium.launch({executablePath:process.env.REVIEW_BROWSER_EXECUTABLE});
 try{
  const page=await browser.newPage();
  const raster=async size=>Buffer.from(await page.evaluate(async({svg,size})=>{
   const image=new Image();image.src='data:image/svg+xml;base64,'+btoa(svg);await image.decode();
   const canvas=document.createElement('canvas');canvas.width=canvas.height=size;
   canvas.getContext('2d').drawImage(image,0,0,size,size);
   return canvas.toDataURL('image/png').split(',')[1];
  },{svg:assets['favicon.svg'],size}),'base64');
  await writeFile(new URL('public/apple-touch-icon.png',root),await raster(180));
  const png=await raster(32),header=Buffer.alloc(22);
  header.writeUInt16LE(1,2);header.writeUInt16LE(1,4);header[6]=header[7]=32;
  header.writeUInt16LE(1,10);header.writeUInt16LE(32,12);header.writeUInt32LE(png.length,14);header.writeUInt32LE(22,18);
  await writeFile(new URL('public/favicon.ico',root),Buffer.concat([header,png]));
 }finally{await browser.close();}
 console.log('Generated theme-derived SVG wordmark/icon, favicon SVG/ICO32 and touch PNG180.');
}
